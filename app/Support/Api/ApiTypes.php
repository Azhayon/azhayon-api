<?php

namespace App\Support\Api;

use InvalidArgumentException;

/** Turns the contract into the TypeScript file the frontend imports. */
final class ApiTypes
{
    /** Definitions whose TypeScript is written by hand in the preamble. */
    private const HANDWRITTEN = ['ContentNode'];

    public static function generate(): string
    {
        $output = self::preamble();

        foreach (Contract::definitions() as $name => $shape) {
            if (in_array($name, self::HANDWRITTEN, true)) {
                continue;
            }

            $output .= self::declaration($name, $shape)."\n\n";
        }

        return rtrim($output)."\n";
    }

    private static function declaration(string $name, mixed $shape): string
    {
        $isObject = is_array($shape) && ! in_array(array_key_first($shape), ['*', '**'], true);

        return $isObject
            ? "export interface {$name} ".self::object($shape, 0)
            : "export type {$name} = ".self::node($shape, 0).';';
    }

    /** @param  array<string, mixed>  $shape */
    private static function object(array $shape, int $level): string
    {
        $pad = str_repeat('  ', $level + 1);
        $lines = [];

        foreach ($shape as $key => $node) {
            $lines[] = $pad.self::key((string) $key).': '.self::node($node, $level + 1).';';
        }

        return "{\n".implode("\n", $lines)."\n".str_repeat('  ', $level).'}';
    }

    private static function key(string $key): string
    {
        return preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $key) ? $key : "'{$key}'";
    }

    private static function node(mixed $node, int $level): string
    {
        if (! is_array($node)) {
            return self::scalar((string) $node);
        }

        $first = array_key_first($node);

        if ($first === '*') {
            $element = self::node($node['*'], $level);

            return (str_contains($element, ' | ') ? "({$element})" : $element).'[]';
        }

        if ($first === '**') {
            return 'Record<string, '.self::node($node['**'], $level).'>';
        }

        return self::object($node, $level);
    }

    private static function scalar(string $node): string
    {
        $parts = array_map(self::alternative(...), array_map('trim', explode('|', ltrim($node, '?'))));

        if (str_starts_with($node, '?')) {
            $parts[] = 'null';
        }

        return implode(' | ', array_values(array_unique($parts)));
    }

    private static function alternative(string $type): string
    {
        return match (true) {
            $type === 'string' => 'string',
            $type === 'int', $type === 'number' => 'number',
            $type === 'bool' => 'boolean',
            $type === 'null' => 'null',
            $type === 'any' => 'unknown',
            $type === 'literal:true' => 'true',
            $type === 'literal:false' => 'false',
            str_starts_with($type, 'enum:') => implode(' | ', array_map(
                fn (string $value): string => "'{$value}'",
                explode(',', substr($type, 5)),
            )),
            str_starts_with($type, '@') => substr($type, 1),
            default => throw new InvalidArgumentException("Unknown contract type: {$type}"),
        };
    }

    private static function preamble(): string
    {
        return <<<'TS'
/* eslint-disable */
// Generated by `php artisan api:types` from app/Support/Api/Contract.php in the API repository.
// Do not edit by hand: change the contract, regenerate, and copy this file to
// azhayon-web/src/lib/api-types.ts.

// ---- Post content: the JSON stored in a post's body ----

export interface BoldMark { type: 'bold' }
export interface ItalicMark { type: 'italic' }
export interface LinkMark { type: 'link'; attrs: { href: string } }
export type TextMark = BoldMark | ItalicMark | LinkMark;

export interface TextNode { type: 'text'; text: string; marks?: TextMark[] }
export interface HardBreakNode { type: 'hardBreak' }
export type InlineNode = TextNode | HardBreakNode;

export interface ParagraphNode { type: 'paragraph'; content?: InlineNode[] }
export interface HeadingNode { type: 'heading'; attrs: { level: 2 | 3 | 4 }; content: InlineNode[] }
export interface HorizontalRuleNode { type: 'horizontalRule' }
export interface ListItemNode { type: 'listItem'; content: Array<ParagraphNode | BulletListNode | OrderedListNode> }
export interface BulletListNode { type: 'bulletList'; content: ListItemNode[] }
export interface OrderedListNode { type: 'orderedList'; attrs?: { start: number }; content: ListItemNode[] }
export interface BlockquoteNode { type: 'blockquote'; content: Array<ParagraphNode | BulletListNode | OrderedListNode> }

export interface ImageBlockNode { type: 'customBlock'; attrs: { id: 'image'; config: ImageBlockConfig } }
export interface YouTubeBlockNode { type: 'customBlock'; attrs: { id: 'youtube'; config: YouTubeBlockConfig } }
export interface XPostBlockNode { type: 'customBlock'; attrs: { id: 'x-post'; config: XPostBlockConfig } }
export interface SpoilerBlockNode { type: 'customBlock'; attrs: { id: 'spoiler'; config: SpoilerBlockConfig } }
export interface AdBreakBlockNode { type: 'customBlock'; attrs: { id: 'ad-break'; config: [] } }
export type CustomBlockNode = ImageBlockNode | YouTubeBlockNode | XPostBlockNode | SpoilerBlockNode | AdBreakBlockNode;

/** A top-level node of a post body. */
export type ContentNode =
  | ParagraphNode
  | HeadingNode
  | BulletListNode
  | OrderedListNode
  | BlockquoteNode
  | HorizontalRuleNode
  | CustomBlockNode;

// ---- Responses and the types they are built from ----


TS;
    }
}